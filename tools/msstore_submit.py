def load_creds():
    path = Path(os.environ.get("MSSTORE_ENV_FILE") or Path.home() / ".secrets/megapdf-msstore.env")
    if not path.is_file():
        die("credentials file not found (set MSSTORE_ENV_FILE or create ~/.secrets/megapdf-msstore.env)")
    creds = {}
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, _, v = line.partition("=")
        creds[k.strip()] = v.strip().strip('"').strip("'")
    missing = [k for k in ("MSSTORE_TENANT_ID", "MSSTORE_CLIENT_ID", "MSSTORE_CLIENT_SECRET")
               if not creds.get(k)]
    if missing:
        die("credentials file lacks " + ", ".join(missing))
    return creds


_TOKEN = None


def token():
    global _TOKEN
    if _TOKEN:
        return _TOKEN
    c = load_creds()
    body = urllib.parse.urlencode({
        "grant_type": "client_credentials", "client_id": c["MSSTORE_CLIENT_ID"],
        "client_secret": c["MSSTORE_CLIENT_SECRET"], "resource": RESOURCE}).encode()
    url = f"https://login.microsoftonline.com/{urllib.parse.quote(c['MSSTORE_TENANT_ID'])}/oauth2/token"
    try:
        with urllib.request.urlopen(urllib.request.Request(url, data=body), timeout=60) as r:
            _TOKEN = json.load(r)["access_token"]
    except urllib.error.HTTPError as e:
        try:
            err = json.load(e)
            detail = f"{err.get('error')}: {err.get('error_description', '').splitlines()[0]}"
        except Exception:
            detail = ""
        die(f"sign-in failed, HTTP {e.code} {detail}")
    return _TOKEN


def api(method, path, body=None, ok=(200, 201, 204)):
    url = path if path.startswith("https://") else API + path
    data = json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(url, data=data, method=method, headers={
        "Authorization": f"Bearer {token()}", "Content-Type": "application/json"})
    for attempt in range(4):
        try:
            with urllib.request.urlopen(req, timeout=120) as r:
                raw = r.read()
                return json.loads(raw) if raw else None
        except urllib.error.HTTPError as e:
            raw = e.read().decode("utf-8", "replace")
            if e.code in (429, 500, 502, 503) and attempt < 3:
                time.sleep(10 * (attempt + 1))
                continue
            die(f"{method} {path} -> HTTP {e.code}: {raw[:1500]}")


def redacted(sub):
    s = json.loads(json.dumps(sub))
    if "fileUploadUrl" in s:
        s["fileUploadUrl"] = "<redacted SAS URL>"
    return s


def describe_submission(sub, label):
    print(f"{label}: id {sub.get('id')}  status {sub.get('status')}  "
          f"publish {sub.get('targetPublishMode')}")
    for p in sub.get("applicationPackages", []):
        print(f"  package {p.get('fileName')}  v{p.get('version')}  {p.get('architecture')}  "
              f"{p.get('fileStatus')}  langs {','.join(p.get('languages') or [])}")
    for lang, l in sorted(sub.get("listings", {}).items()):
        b = l.get("baseListing", {})
        imgs = [i for i in b.get("images", []) if i.get("imageType") == "Screenshot"]
        print(f"  {lang}: title '{b.get('title')}', description {len(b.get('description') or '')}, "
              f"what's new {len(b.get('releaseNotes') or '')}, {len(b.get('features') or [])} features, "
              f"{len(b.get('keywords') or [])} search terms, {len(imgs)} screenshots "
              f"({', '.join(sorted(set(i.get('fileStatus', '?') for i in imgs)))})")
    pr = sub.get("pricing", {})
    print(f"  pricing {pr.get('priceId')}  visibility {sub.get('visibility')}")


def cmd_status(_args):
    app = api("GET", f"/applications/{APP_ID}")
    print(f"app {app.get('id')}  '{app.get('primaryName')}'  package family {app.get('packageFamilyName')}")
    pub = app.get("lastPublishedApplicationSubmission")
    pend = app.get("pendingApplicationSubmission")
    if pub:
        describe_submission(api("GET", f"/applications/{APP_ID}/submissions/{pub['id']}"),
                            "published submission")
    if pend:
        sub = api("GET", f"/applications/{APP_ID}/submissions/{pend['id']}")
        describe_submission(sub, "PENDING submission")
        st = api("GET", f"/applications/{APP_ID}/submissions/{pend['id']}/status")
        print(f"  status {st.get('status')}  details {json.dumps(st.get('statusDetails'))[:1500]}")
    else:
        print("no pending submission")


def apply_payload(sub, payload):
    """Mutate a submission JSON so it carries this release."""
    for p in sub.get("applicationPackages", []):
        p["fileStatus"] = "PendingDelete"
    for p in payload["packages"]:
        sub.setdefault("applicationPackages", []).append({
            "fileName": p["fileName"], "fileStatus": "PendingUpload",
            "minimumDirectXVersion": "None", "minimumSystemRam": "None"})
    sub["targetPublishMode"] = "Immediate"
    sub["targetPublishDate"] = None
    sub["notesForCertification"] = payload["notesForCertification"]
    listings = sub.setdefault("listings", {})
    for lang, want in payload["listings"].items():
        l = listings.setdefault(lang, {"baseListing": {}, "platformOverrides": {}})
        b = l.setdefault("baseListing", {})
        for im in b.get("images", []):
            if im.get("imageType") == "Screenshot":
                im["fileStatus"] = "PendingDelete"
        for k, v in want.items():
            if k != "images":
                b[k] = v
        b.setdefault("images", []).extend(
            {"fileName": im["fileName"], "fileStatus": "PendingUpload",
             "description": im["description"], "imageType": "Screenshot"}
            for im in want["images"])
    return sub


def cmd_plan(args):
    payload, _ = build_payload(Path(args.out), Path(args.artifacts) / "store")
    app = api("GET", f"/applications/{APP_ID}")
    pub = app.get("lastPublishedApplicationSubmission") or die("no published submission to base on")
    sub = api("GET", f"/applications/{APP_ID}/submissions/{pub['id']}")
    describe_submission(sub, "published (before)")
    describe_submission(apply_payload(sub, payload), "planned (after)")
    extra = sorted(set(sub.get("listings", {})) - set(payload["listings"]))
    if extra:
        print(f"  note: listings not touched by this payload: {', '.join(extra)}")


def upload(zpath, sas):
    size = zpath.stat().st_size
    with open(zpath, "rb") as f:
        req = urllib.request.Request(sas, data=f, method="PUT", headers={
            "x-ms-blob-type": "BlockBlob", "x-ms-version": "2020-04-08",
            "Content-Length": str(size), "Content-Type": "application/zip"})
        try:
            with urllib.request.urlopen(req, timeout=3600) as r:
                print(f"uploaded {size / 1e6:.1f} MB, HTTP {r.status}")
        except urllib.error.HTTPError as e:
            die(f"upload failed, HTTP {e.code}: {e.read()[:500]!r}")


def cmd_poll(args, sid=None):
    sid = sid or args.id
    last = None
    deadline = time.time() + args.timeout
    while True:
        st = api("GET", f"/applications/{APP_ID}/submissions/{sid}/status")
        s = st.get("status")
        if s != last:
            print(f"{time.strftime('%H:%M:%S')} {s}")
            last = s
        det = st.get("statusDetails") or {}
        if s == "CommitFailed" or det.get("errors"):
            print(json.dumps(det, indent=2)[:4000])
            if s == "CommitFailed":
                sys.exit(2)
        if s not in ("CommitStarted", "PendingCommit", "PreProcessing"):
            if det.get("warnings"):
                print("warnings:", json.dumps(det["warnings"], indent=2)[:3000])
            return s
        if time.time() > deadline:
            die(f"still {s} after {args.timeout}s; poll again with: msstore_submit.py poll {sid}")
        time.sleep(30)


def cmd_submit(args):
    payload, zpath = build_payload(Path(args.out), Path(args.artifacts) / "store")
    summarize(payload, zpath)
    app = api("GET", f"/applications/{APP_ID}")
    if app.get("pendingApplicationSubmission"):
        die(f"a pending submission already exists ({app['pendingApplicationSubmission']['id']}); "
            "inspect it with `status` and delete it in Partner Center (or via the API) first")
    sub = api("POST", f"/applications/{APP_ID}/submissions")
    sid = sub["id"]
    print(f"created submission {sid}")
    sas = sub["fileUploadUrl"]
    sub = apply_payload(sub, payload)
    updated = api("PUT", f"/applications/{APP_ID}/submissions/{sid}", sub)
    describe_submission(updated, "updated")
    (Path(args.out) / "submission.json").write_text(
        json.dumps(redacted(updated), ensure_ascii=False, indent=2), encoding="utf-8")
    upload(zpath, sas)
    api("POST", f"/applications/{APP_ID}/submissions/{sid}/commit")
    print(f"committed {sid}")
    final = cmd_poll(args, sid)
    print(f"submission {sid}: {final}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("command", choices=["build", "token-test", "status", "plan", "submit", "poll"])
    ap.add_argument("id", nargs="?")
    ap.add_argument("--artifacts", default=str(REPO / "artifacts"),
                    help="the artifacts folder holding store/rc-<ver>/ and store/screenshots/")
    ap.add_argument("--out", help="where payload.json, upload.zip and submission.json go "
                    "(default <artifacts>/store/msstore-<ver>)")
    ap.add_argument("--timeout", type=int, default=3600)
    args = ap.parse_args()
    args.out = args.out or str(Path(args.artifacts) / f"store/msstore-{VERSION}")
    if args.command == "build":
        payload, zpath = build_payload(Path(args.out), Path(args.artifacts) / "store")
        summarize(payload, zpath)
    elif args.command == "token-test":
        token()
        print("token OK")
    elif args.command == "status":
        cmd_status(args)
    elif args.command == "plan":
        cmd_plan(args)
    elif args.command == "submit":
        cmd_submit(args)
    elif args.command == "poll":
        if not args.id:
            die("poll needs a submission id")
        cmd_poll(args)


if __name__ == "__main__":
    main()
