#!/usr/bin/env python3
"""Microsoft Store submission through the Store submission API (#146 §4).

Partner Center's own REST API, driven by the Microsoft Entra application
"MegaPDF submission" (Manager role). Nothing here opens a browser; nothing here
prints a credential, a token or the upload URL.

Credentials come from a KEY=VALUE file, never from argv or the environment dump:
MSSTORE_ENV_FILE if set, else ~/.secrets/megapdf-msstore.env (0600), holding
MSSTORE_TENANT_ID, MSSTORE_CLIENT_ID and MSSTORE_CLIENT_SECRET (MSSTORE_SELLER_ID
may sit beside them; this API does not need it).

  msstore_submit.py build        write payload.json + upload.zip under --out; no network
  msstore_submit.py token-test   sign in and print only "token OK" or the HTTP status
  msstore_submit.py status       read back the app, its published and pending submissions
  msstore_submit.py plan         apply the payload to a copy of the published submission,
                                 locally, and print what would change; creates nothing
  msstore_submit.py submit       create the submission, fill it, upload, commit, poll
  msstore_submit.py poll ID      poll a submission's status until certification starts

Content is read from the repo, never typed here: the listing copy from
docs/microsoft-store-listing.md (generated by tools/gen_listing_copy.py), What's
new from docs/release-notes/<ver>/microsoft-store.md, screenshots from
artifacts/store/screenshots/<lang>/0N-*.png and the packages from
artifacts/store/rc-<ver>/, each checked against that folder's SHA256SUMS.
"""
