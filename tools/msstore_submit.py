import hashlib
import json
import os
import re
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
import zipfile
from pathlib import Path

APP_ID = "9PF4TRRH4M76"          # Store ID of "Mega PDF"
TITLE = "Mega PDF"               # must match the name reserved in Partner Center
API = "https://manage.devcenter.microsoft.com/v1.0/my"
RESOURCE = "https://manage.devcenter.microsoft.com"
VERSION = "2.0.0.0"
REPO = Path(__file__).resolve().parent.parent

# Partner Center listing language -> the screenshot set and the release-notes block
LANGS = {
    "en-us": {"shots": "en", "doc": "en-US"},
    "en-ca": {"shots": "en", "doc": "en-CA"},
    "fr-ca": {"shots": "fr-CA", "doc": "fr-CA"},
    "fr-fr": {"shots": "fr-FR", "doc": "fr-FR"},
}
LIMITS = {"description": 10000, "shortDescription": 1000, "releaseNotes": 1500,
          "feature": 200, "features": 20, "keyword": 30, "keywords": 7,
          "keywordWords": 21, "caption": 200, "copyright": 200}

CERT_NOTES = (
    "MegaPDF 2.0 is a local PDF editor: no account, no sign-in, no network use. "
    "To try it, open any PDF (File > Open, or double-click a .pdf once the app is the "
    "default). Click text to edit it, click an empty square to tick it, use Redact to "
    "remove a name from the file, and Save. This submission replaces both 1.7 packages: "
    "the new ARM64 package carries ARM64 native libraries (the 1.7 ARM64 package did not "
    "and could not open documents)."
)


def die(msg):
    print(f"error: {msg}", file=sys.stderr)
    sys.exit(1)


# ---------------------------------------------------------------- content

def fenced_after(lines, i):
    """Text of the first ``` block at or after line i, and the index past it."""
    while i < len(lines) and not lines[i].startswith("```"):
        i += 1
    if i >= len(lines):
        return None, i
    j = i + 1
    body = []
    while j < len(lines) and not lines[j].startswith("```"):
        body.append(lines[j])
        j += 1
    return "\n".join(body).strip("\n"), j + 1


def parse_listing_doc(path):
    text = path.read_text(encoding="utf-8")
    m = re.search(r"<!-- copy-by-language -->(.*)<!-- /copy-by-language -->", text, re.S)
    if not m:
        die(f"{path}: no copy-by-language section")
    out = {}
    for sect in re.split(r"^### ", m.group(1), flags=re.M)[1:]:
        code = re.search(r"`([a-z]{2}-[A-Z]{2})`", sect.splitlines()[0])
        if not code:
            continue
        lines = sect.splitlines()
        fields = {}
        i = 0
        while i < len(lines):
            head = re.match(r"\*\*([^*]+)\*\*", lines[i])
            if head:
                body, i = fenced_after(lines, i + 1)
                fields[head.group(1).strip()] = body
                continue
            i += 1
        def pick(prefix):
            for k, v in fields.items():
                if k.startswith(prefix):
                    return v
            die(f"{path}: {code.group(1)} has no '{prefix}' block")
        captions = {}
        for line in pick("Screenshot captions").splitlines():
            name, _, cap = line.partition(": ")
            captions[name.strip()] = cap.strip()
        out[code.group(1)] = {
            "shortDescription": pick("Short description"),
            "description": pick("Description"),
            "features": [l.strip() for l in pick("App features").splitlines() if l.strip()],
            "keywords": [l.strip() for l in pick("Search terms").splitlines() if l.strip()],
            "copyright": pick("Copyright"),
            "captions": captions,
        }
    other = text.split("## Other fields", 1)[1].split("\n## ", 1)[0].splitlines()
    vals = []
    i = 0
    while len(vals) < 3:
        body, i = fenced_after(other, i)
        if body is None:
            die(f"{path}: Other fields has fewer than three blocks")
        vals.append(body.strip())
    return out, {"privacyPolicy": vals[0], "websiteUrl": vals[1], "supportContact": vals[2]}


def parse_release_notes(path):
    lines = path.read_text(encoding="utf-8").splitlines()
    notes = {}
    codes = []
    i = 0
    while i < len(lines):
        if lines[i].startswith("## "):
            codes = re.findall(r"`([a-z]{2}-[A-Z]{2})`", lines[i])
        if codes and lines[i].startswith("```"):
            body, i = fenced_after(lines, i)
            for c in codes:
                notes[c] = body
            codes = []
            continue
        i += 1
    return notes


def check_packages(rc_dir):
    """The two upload packages, each matching its line in rc_dir/SHA256SUMS."""
    sums = {}
    for line in (rc_dir / "SHA256SUMS").read_text().splitlines():
        parts = line.split()
        if len(parts) == 2 and not line.startswith("#") and "not-for-upload" not in parts[1]:
            sums[Path(parts[1]).name] = parts[0]
    pkgs = []
    for arch in ("x64", "arm64"):
        p = rc_dir / f"MegaPDF.App_{VERSION}_{arch}.msix"
        if not p.is_file():
            die(f"missing {p}")
        h = hashlib.sha256(p.read_bytes()).hexdigest()
        if sums.get(p.name) != h:
            die(f"{p.name}: sha256 {h[:12]}… does not match SHA256SUMS")
        pkgs.append((p, h))
    return pkgs


def build_payload(out, art):
    listing, other = parse_listing_doc(REPO / "docs/microsoft-store-listing.md")
    ver = VERSION.rsplit(".", 2)[0]  # 2.0
    notes = parse_release_notes(REPO / f"docs/release-notes/{ver}/microsoft-store.md")
    pkgs = check_packages(art / f"rc-{VERSION}")
    problems = []
    payload = {"appId": APP_ID, "version": VERSION, "targetPublishMode": "Immediate",
               "notesForCertification": CERT_NOTES, "packages": [], "listings": {}}
    files = []
    for p, h in pkgs:
        rel = f"packages/{p.name}"
        payload["packages"].append({"fileName": rel, "sha256": h})
        files.append((p, rel))
    for lang, m in LANGS.items():
        src = listing.get(m["doc"]) or die(f"listing doc has no {m['doc']}")
        rn = notes.get(m["doc"]) or die(f"release notes have no {m['doc']}")
        shots = sorted((art / "screenshots" / m["shots"]).glob("0[1-9]-*.png"))
        if [s.name for s in shots] != list(src["captions"]):
            problems.append(f"{lang}: screenshots {[s.name for s in shots]} "
                            f"!= captions {list(src['captions'])}")
        images = []
        for s in shots:
            rel = f"images/{m['shots']}/{s.name}"
            if (s, rel) not in files:
                files.append((s, rel))
            images.append({"fileName": rel, "description": src["captions"].get(s.name, "")})
        base = {
            "title": TITLE,
            "shortDescription": src["shortDescription"],
            "description": src["description"],
            "features": src["features"],
            "keywords": src["keywords"],
            "releaseNotes": rn,
            "copyrightAndTrademarkInfo": src["copyright"],
            **other,
            "images": images,
        }
        for k in ("description", "shortDescription", "releaseNotes"):
            if len(base[k]) > LIMITS[k]:
                problems.append(f"{lang}: {k} {len(base[k])} > {LIMITS[k]}")
        if len(base["copyrightAndTrademarkInfo"]) > LIMITS["copyright"]:
            problems.append(f"{lang}: copyright too long")
        if len(base["features"]) > LIMITS["features"]:
            problems.append(f"{lang}: {len(base['features'])} features > {LIMITS['features']}")
        for f in base["features"]:
            if len(f) > LIMITS["feature"]:
                problems.append(f"{lang}: feature {len(f)} > {LIMITS['feature']}: {f[:40]}…")
        if len(base["keywords"]) > LIMITS["keywords"]:
            problems.append(f"{lang}: {len(base['keywords'])} search terms > {LIMITS['keywords']}")
        for k in base["keywords"]:
            if len(k) > LIMITS["keyword"]:
                problems.append(f"{lang}: search term {len(k)} > {LIMITS['keyword']}: {k}")
        words = sum(len(k.split()) for k in base["keywords"])
        if words > LIMITS["keywordWords"]:
            problems.append(f"{lang}: search terms use {words} words > {LIMITS['keywordWords']}")
        for im in images:
            if len(im["description"]) > LIMITS["caption"]:
                problems.append(f"{lang}: caption {len(im['description'])} > {LIMITS['caption']}")
            if not im["description"]:
                problems.append(f"{lang}: {im['fileName']} has no caption")
        payload["listings"][lang] = base
    if problems:
        die("content check failed:\n  " + "\n  ".join(problems))
    out.mkdir(parents=True, exist_ok=True)
    (out / "payload.json").write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    zpath = out / "upload.zip"
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_STORED) as z:
        for src, rel in files:
            z.write(src, rel)
    return payload, zpath


def summarize(payload, zpath=None):
    print(f"app {payload['appId']}  version {payload['version']}  publish {payload['targetPublishMode']}")
    for p in payload["packages"]:
        print(f"  package {p['fileName']}  sha256 {p['sha256'][:12]}…")
    for lang, b in payload["listings"].items():
        print(f"  {lang}: title '{b['title']}', description {len(b['description'])}/10000, "
              f"short {len(b['shortDescription'])}, what's new {len(b['releaseNotes'])}/1500, "
              f"{len(b['features'])} features (longest {max(map(len, b['features']))}/200), "
              f"{len(b['keywords'])} search terms (longest {max(map(len, b['keywords']))}/30), "
              f"{len(b['images'])} screenshots")
    if zpath:
        with zipfile.ZipFile(zpath) as z:
            n = len(z.namelist())
        print(f"  upload.zip: {n} files, {zpath.stat().st_size / 1e6:.1f} MB")


