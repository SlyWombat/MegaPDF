#!/usr/bin/env python3
"""Generate the typed string accessors for the two desktop apps, and the
pseudo-locale used to check layouts before a translation exists (#91).

The English catalogue is the source of truth on each desktop platform:

    src/MegaPDF.App/Strings/en-US/Resources.resw      (Windows, MRT / x:Uid)
    src/MegaPDF.Avalonia/Strings/Strings.resx         (macOS, ResourceManager)

Neither `dotnet build` runs a ResX designer generator without Visual Studio,
so this script writes the accessor class instead. Run from anywhere:

    python3 tools/gen_strings.py            # regenerate both Strings.g.cs
    python3 tools/gen_strings.py fr-fr      # also derive France French from Canadian
    python3 tools/gen_strings.py es-es      # also derive Spain Spanish from Latin American (#724)
    python3 tools/gen_strings.py fr-fr es-es   # both, as CI runs it
    python3 tools/gen_strings.py pseudo     # also write the qps-ploc catalogues

`fr-fr` outputs (committed, checked for drift by ci.yml):
    src/MegaPDF.App/Strings/fr-FR/Resources.resw
    src/MegaPDF.Avalonia/Strings/Strings.fr.resx
    android/app/src/main/res/values-fr/strings.xml
    the "fr" localizations inside ios/MegaPDF/Localizable.xcstrings

`es-es` outputs (committed, checked for drift by ci.yml):
    src/MegaPDF.App/Strings/es-ES/Resources.resw
    src/MegaPDF.Avalonia/Strings/Strings.es-ES.resx
    android/app/src/main/res/values-es/strings.xml
    the "es" localizations inside ios/MegaPDF/Localizable.xcstrings

Outputs (committed, checked for drift by ci.yml):
    src/MegaPDF.App/Strings.g.cs
    src/MegaPDF.Avalonia/Strings.g.cs

`pseudo` outputs (gitignored, never shipped) — accented, ~30 % longer copies of
the English so hard-coded strings and clipped layouts show up before the
French does:
    src/MegaPDF.App/Strings/qps-ploc/Resources.resw
    src/MegaPDF.Avalonia/Strings/Strings.qps-ploc.resx

Conventions the generator relies on:
  * A key containing a dot (`LabelOpen.Text`) is a XAML x:Uid property and gets
    no accessor — XAML resolves it directly.
  * A value containing `{0}`-style placeholders becomes a method taking one
    argument per placeholder and formatting with CurrentCulture.
  * Everything else is a static property.
"""

import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

WINDOWS_RESW = ROOT / "src/MegaPDF.App/Strings/en-US/Resources.resw"
WINDOWS_OUT = ROOT / "src/MegaPDF.App/Strings.g.cs"
WINDOWS_PSEUDO = ROOT / "src/MegaPDF.App/Strings/qps-ploc/Resources.resw"

MAC_RESX = ROOT / "src/MegaPDF.Avalonia/Strings/Strings.resx"
MAC_OUT = ROOT / "src/MegaPDF.Avalonia/Strings.g.cs"
MAC_PSEUDO = ROOT / "src/MegaPDF.Avalonia/Strings/Strings.qps-ploc.resx"

PLACEHOLDER = re.compile(r"\{(\d+)(?:[:,][^}]*)?\}")


def read_catalogue(path: Path) -> list[tuple[str, str, str]]:
    """(name, value, comment) for every <data> entry, in file order."""
    entries = []
    for data in ET.parse(path).getroot().findall("data"):
        name = data.get("name")
        value = data.findtext("value") or ""
        comment = data.findtext("comment") or ""
        entries.append((name, value, comment))
    return entries


def accessor(name: str, value: str) -> str:
    slots = sorted({int(n) for n in PLACEHOLDER.findall(value)})
    summary = value.replace("\n", " ").replace("&", "&amp;").replace("<", "&lt;")
    lines = [f"    /// <summary>{summary}</summary>"]
    if not slots:
        lines.append(f"    public static string {name} => Get(\"{name}\");")
    else:
        expected = list(range(len(slots)))
        if slots != expected:
            raise SystemExit(f"{name}: placeholders must be {{0}}..{{n}} without gaps, got {slots}")
        params = ", ".join(f"object? arg{i}" for i in slots)
        args = ", ".join(f"arg{i}" for i in slots)
        lines.append(
            f"    public static string {name}({params}) => "
            f"string.Format(CultureInfo.CurrentCulture, Get(\"{name}\"), {args});"
        )
    return "\n".join(lines)


def generate(entries, namespace: str, source: str, loader: str) -> str:
    body = "\n\n".join(accessor(n, v) for n, v, _ in entries if "." not in n)
    return f"""// <auto-generated>
//   Generated by tools/gen_strings.py from {source}.
//   Do not edit: change the catalogue and re-run the script.
// </auto-generated>
#nullable enable
using System.Globalization;

namespace {namespace};

/// <summary>
/// Typed access to the English catalogue's keys (#91). Every user-facing string
/// in code goes through here, so a missing key is a compile error rather than a
/// runtime blank.
/// </summary>
public static partial class Strings
{{
{loader}

{body}
}}
"""


WINDOWS_LOADER = """    private static string Get(string key) => AppLanguage.GetString(key);"""

MAC_LOADER = """    private static readonly System.Resources.ResourceManager Manager =
        new("MegaPDF.Avalonia.Strings.Strings", typeof(Strings).Assembly);

    private static string Get(string key) =>
        Manager.GetString(key, CultureInfo.CurrentUICulture) ?? key;"""


# --- pseudo-localisation -----------------------------------------------------

ACCENTS = str.maketrans(
    "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ",
    "åƀçđéƒģĥïĵķļɱñöþqŕşŧûṽŵẋÿžÅƁÇĐÉƑĢĤÏĴĶĻɱÑÖÞQŔŞŦÛṼŴẊŸŽ",
)


def pseudo(value: str) -> str:
    """Accent every letter, keep placeholders intact, pad by ~30 %."""
    out = []
    last = 0
    for m in PLACEHOLDER.finditer(value):
        out.append(value[last:m.start()].translate(ACCENTS))
        out.append(m.group(0))
        last = m.end()
    out.append(value[last:].translate(ACCENTS))
    text = "".join(out)
    pad = "~" * max(1, round(len(value) * 0.3))
    return f"[{text}{pad}]"


def write_pseudo(source: Path, target: Path) -> None:
    tree = ET.parse(source)
    for data in tree.getroot().findall("data"):
        v = data.find("value")
        if v is not None and v.text:
            v.text = pseudo(v.text)
    target.parent.mkdir(parents=True, exist_ok=True)
    tree.write(target, encoding="utf-8", xml_declaration=True)


# --- France French, derived from Canadian French ---------------------------
#
# The two differ by a short list of words and by punctuation, not by
# sentences, so the France catalogues are generated from the Canadian ones
# rather than maintained by hand: one French to translate, one table to keep.
# Edit the table, not the derived files — CI regenerates and diffs them.

FR_CA_TO_FR_FR = [
    # (Canadian, France) — order matters, longer phrases first. The contracted
    # articles go first too: "au courriel" is "à l'e-mail", never "au e-mail".
    ("au courriel", "à l'e-mail"),
    ("du courriel", "de l'e-mail"),
    ("pour le courriel", "pour l'e-mail"),
    ("pour courriel", "pour l'e-mail"),
    ("courriel", "e-mail"),
    ("Courriel", "E-mail"),
    # Quebec's téléverser is understood in France, but a French reader writes envoyer.
    ("téléversé nulle part", "envoyé nulle part"),
    ("d'infonuagique", "de cloud"),
    ("infonuagique", "cloud"),
    ("crochet", "coche"),
    ("Crochet", "Coche"),
    ("Merci tout spécial à", "Un grand merci à"),
    ("fin de semaine", "week-end"),
    ("ramassage", "enlèvement"),
    # Not a word but a person: the demo signatory in the store captures, who has
    # a different name per listing language (#146 §3, Dave 2026-09-15). The iOS and
    # Android catalogues carry it; the Mac reads its copy from DemoContent.cs.
    ("Hélène Bélanger", "Céline Lefèvre"),
    # Nor this: the demo agreement the phones' captures open (#310). fr-CA opens
    # demo-fr.pdf, the Quebec page; fr-FR opens demo-fr-FR.pdf, France's own text
    # (tools/gen_test_fixtures.py DEMO_TEXT). Android's screenshot_demo_asset and
    # the iOS catalogue's "demo" key both carry the name.
    ("demo-fr", "demo-fr-FR"),
    ("Français (Canada)", "Français (Canada)"),  # language names never change
]

# France puts a non-breaking space before ? ! ; as well as : (Quebec: : only).
#
# This matches any run of whitespace (including none) immediately before the
# punctuation \u2014 not just "no whitespace at all" \u2014 and replaces the whole run
# with a single U+00A0. A narrower pattern that only matched when there was
# *no* preceding character (e.g. an `(?<=[^\s\u00a0])` lookbehind) would see
# an existing plain space as "already has something there" and skip the
# insertion entirely, silently shipping that plain space into fr-FR instead
# of the required non-breaking one. Matching the whole run and normalising it
# handles "no space", "a stray plain space" and "an existing nbsp" the same
# way, and is idempotent: re-running it on already-correct output (one nbsp)
# replaces that nbsp with itself.
FRANCE_PUNCTUATION = re.compile(r"\s*([?!;])")
XML_ENTITY = re.compile(r"&#?\w+;")


def to_france(value: str) -> str:
    for ca, fr in FR_CA_TO_FR_FR:
        value = value.replace(ca, fr)
    # Entities such as &#160; end in ";" — keep the punctuation rule off them.
    out, last = [], 0
    for m in XML_ENTITY.finditer(value):
        out.append(FRANCE_PUNCTUATION.sub("\u00a0\\1", value[last:m.start()]))
        out.append(m.group(0))
        last = m.end()
    out.append(FRANCE_PUNCTUATION.sub("\u00a0\\1", value[last:]))
    return "".join(out)


def derive_xml_values(text: str, pattern: str, escape=lambda value: value) -> str:
    """Apply to_france inside the element bodies `pattern` captures, leaving the
    file's comments and formatting alone. `escape` then fixes up what the table
    put in for the target format."""
    return re.sub(pattern, lambda m: m.group(1) + escape(to_france(m.group(2))) + m.group(3), text, flags=re.S)


def android_escape(value: str) -> str:
    """An Android string resource needs every apostrophe escaped, and the table's
    France wording brings new ones ("pour l'e-mail", #593); aapt2 refuses a bare one."""
    return re.sub(r"(?<!\\)'", r"\\'", value)


WINDOWS_FR_CA = ROOT / "src/MegaPDF.App/Strings/fr-CA/Resources.resw"
WINDOWS_FR_FR = ROOT / "src/MegaPDF.App/Strings/fr-FR/Resources.resw"
MAC_FR_CA = ROOT / "src/MegaPDF.Avalonia/Strings/Strings.fr-CA.resx"
MAC_FR_FR = ROOT / "src/MegaPDF.Avalonia/Strings/Strings.fr.resx"
ANDROID_FR_CA = ROOT / "android/app/src/main/res/values-fr-rCA/strings.xml"
ANDROID_FR_FR = ROOT / "android/app/src/main/res/values-fr/strings.xml"
IOS_CATALOG = ROOT / "ios/MegaPDF/Localizable.xcstrings"

DERIVED_HEADER = "DERIVED FILE — generated by `tools/gen_strings.py fr-fr` from the Canadian French catalogue. Edit that file, or the FR_CA_TO_FR_FR table, never this one."


def write_france() -> None:
    xml_value = r"(<value(?: [^>]*)?>)(.*?)(</value>)"
    android_value = r"(<(?:string|item)\b[^>]*>)(.*?)(</(?:string|item)>)"

    for src, dst, pattern, banner, escape in (
        (WINDOWS_FR_CA, WINDOWS_FR_FR, xml_value, "Français (France)", lambda v: v),
        (MAC_FR_CA, MAC_FR_FR, xml_value, "Français (France) — the neutral `fr` culture", lambda v: v),
        (ANDROID_FR_CA, ANDROID_FR_FR, android_value, "Français (France) — the neutral `values-fr`", android_escape),
    ):
        text = src.read_text(encoding="utf-8")
        text = derive_xml_values(text, pattern, escape)
        # Replace the hand-written header comment with the derived-file banner.
        text = re.sub(r"<!--.*?-->", f"<!--\n  {banner}.\n  {DERIVED_HEADER}\n-->", text, count=1, flags=re.S)
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_text(text, encoding="utf-8", newline="\n")
        print(f"{dst.relative_to(ROOT)}: derived from {src.name}")

    # iOS: a second localization inside the same catalog.
    catalog = json.loads(IOS_CATALOG.read_text(encoding="utf-8"))
    count = 0
    for entry in catalog["strings"].values():
        locs = entry.get("localizations")
        if not locs or "fr-CA" not in locs:
            continue
        unit = locs["fr-CA"]["stringUnit"]
        locs["fr"] = {"stringUnit": {"state": unit["state"], "value": to_france(unit["value"])}}
        count += 1
    IOS_CATALOG.write_text(
        json.dumps(catalog, ensure_ascii=False, indent=2, separators=(",", " : "), sort_keys=True) + "\n",
        encoding="utf-8", newline="\n")
    print(f"{IOS_CATALOG.relative_to(ROOT)}: {count} fr entries derived from fr-CA")


# --- Spain Spanish, derived from Latin American Spanish (#724) ----------------
#
# The same shape as France French: es-419 is hand-written, es-ES is generated
# from it by a short word table. Where each catalogue lives differs by
# platform on purpose (docs/localisation.md): the desktops keep Latin American
# in the neutral `es` (MRT and .NET fall back from es-MX to `es` only), the
# phones keep it in `es-419` and Spain in the neutral `es`.
#
# There is no punctuation pass. Spanish has no non-breaking-space rule: never
# call FRANCE_PUNCTUATION on it.

ES_419_TO_ES_ES = [
    # (es-419, es-ES), whole words, case-sensitive, longest first. Article
    # agreement rows go before the bare noun: "la computadora" is "el ordenador".
    ("las computadoras", "los ordenadores"), ("una computadora", "un ordenador"),
    ("la computadora", "el ordenador"), ("esta computadora", "este ordenador"),
    ("computadoras", "ordenadores"), ("computadora", "ordenador"),
    ("Computadora", "Ordenador"),
    ("celulares", "móviles"), ("celular", "móvil"), ("Celular", "Móvil"),
    ("videos", "vídeos"), ("video", "vídeo"), ("Videos", "Vídeos"), ("Video", "Vídeo"),
    ("el mouse", "el ratón"), ("mouse", "ratón"),
    ("Presiona", "Pulsa"), ("presiona", "pulsa"), ("Presionar", "Pulsar"), ("presionar", "pulsar"),
    ("Llenar", "Rellenar"), ("llenar", "rellenar"), ("Llena", "Rellena"), ("llena", "rellena"),
    ("llenado", "rellenado"), ("llenada", "rellenada"),
    ("llenarse", "rellenarse"), ("llenarlo", "rellenarlo"),
    ("presionada", "pulsada"), ("presionado", "pulsado"),
    # Spain says introducir where Latin America says ingresar (the store copy's
    # "los valores que ingresaste").
    ("ingresaste", "introdujiste"), ("ingresados", "introducidos"),
    # Spain reads añadir where Latin America reads agregar (Fable, #724). Every
    # inflection the catalogues and store copy use, with its capitalisation.
    ("Agregar", "Añadir"), ("agregar", "añadir"), ("AGREGAR", "AÑADIR"),
    ("Agregando", "Añadiendo"), ("Agrega", "Añade"), ("agrega", "añade"),
    ("agregas", "añades"), ("agregues", "añadas"), ("agreguen", "añadan"),
    ("Agrégalo", "Añádelo"), ("agregó", "añadió"), ("agregará", "añadirá"),
    ("agregaron", "añadieron"), ("agregadas", "añadidas"), ("agregada", "añadida"),
    ("agregado", "añadido"),
    # Not a word but a person: the demo signatory in the store captures, who has a
    # different name per listing language (D7, Dave 2026-10-21).
    ("Sofía Ramírez", "Lucía Fernández"),
    # Nor this: the demo document the phones' captures open. es-419 opens
    # demo-es.pdf, Latin America's page; es-ES opens demo-es-ES.pdf, Spain's.
    ("demo-es", "demo-es-ES"),
    # The demo document's rental word: es-419 pages say arrendamiento (a contrato de
    # arrendamiento), Spain's say alquiler. The phones' screenshot strings (document
    # name, edited heading, search term) carry it, and the search term must occur in
    # the page the captures open.
    ("arrendamiento", "alquiler"),
    # The phones' document name is a bare noun, so it starts a capital: "Arrendamiento.pdf"
    # (es-419) is "Alquiler.pdf" in Spain. Short on purpose, because the title bar cuts a
    # longer name before the extension (#802).
    ("Arrendamiento", "Alquiler"),
    ("Español (Latinoamérica)", "Español (Latinoamérica)"),  # language names never change
]

# Settings (D6) is a variant split, applied by key and never by word, so that
# "la configuración de seguridad" is left alone. Windows keeps Configuración in
# both variants and so has no entry; the Mac catalogue has no Settings key.
ES_ES_KEY_OVERRIDES = {
    "android": {"settings": "Ajustes"},
    "ios": {"Settings": "Ajustes", "Settings…": "Ajustes…"},
}


def _es_pattern(a: str, b: str) -> "re.Pattern[str]":
    """Whole-word pattern for one table row. A row whose output starts with its
    input (demo-es -> demo-es-ES) must not fire again on its own output, or the
    derivation would not be idempotent."""
    tail = b[len(a):] if b.startswith(a) else ""
    guard = rf"(?!{re.escape(tail)})" if tail else ""
    return re.compile(rf"(?<!\w){re.escape(a)}(?!\w){guard}")


ES_PATTERNS = [(_es_pattern(a, b), b) for a, b in ES_419_TO_ES_ES]


def to_spain(value: str) -> str:
    for pattern, spain in ES_PATTERNS:
        value = pattern.sub(lambda _m, spain=spain: spain, value)
    return value


WINDOWS_ES_419 = ROOT / "src/MegaPDF.App/Strings/es/Resources.resw"
WINDOWS_ES_ES = ROOT / "src/MegaPDF.App/Strings/es-ES/Resources.resw"
MAC_ES_419 = ROOT / "src/MegaPDF.Avalonia/Strings/Strings.es.resx"
MAC_ES_ES = ROOT / "src/MegaPDF.Avalonia/Strings/Strings.es-ES.resx"
ANDROID_ES_419 = ROOT / "android/app/src/main/res/values-b+es+419/strings.xml"
ANDROID_ES_ES = ROOT / "android/app/src/main/res/values-es/strings.xml"

DERIVED_HEADER_ES = "DERIVED FILE — generated by `tools/gen_strings.py es-es` from the Latin American Spanish catalogue. Edit that file, or the ES_419_TO_ES_ES table, never this one."


def derive_es_values(text: str, pattern: str) -> str:
    return re.sub(pattern, lambda m: m.group(1) + to_spain(m.group(2)) + m.group(3), text, flags=re.S)


def write_spain() -> None:
    xml_value = r"(<value(?: [^>]*)?>)(.*?)(</value>)"
    android_value = r"(<(?:string|item)\b[^>]*>)(.*?)(</(?:string|item)>)"

    for src, dst, pattern, banner, platform in (
        (WINDOWS_ES_419, WINDOWS_ES_ES, xml_value, "Español (España)", "windows"),
        (MAC_ES_419, MAC_ES_ES, xml_value, "Español (España) — the es-ES culture", "mac"),
        (ANDROID_ES_419, ANDROID_ES_ES, android_value, "Español (España) — the neutral `values-es`", "android"),
    ):
        text = src.read_text(encoding="utf-8")
        text = derive_es_values(text, pattern)
        for key, value in ES_ES_KEY_OVERRIDES.get(platform, {}).items():
            text, n = re.subn(
                rf'(<string name="{re.escape(key)}"[^>]*>)(.*?)(</string>)',
                lambda m, value=value: m.group(1) + value + m.group(3), text, flags=re.S)
            if n != 1:
                raise SystemExit(f"{src.name}: expected one <string name=\"{key}\">, found {n}")
        text = re.sub(r"<!--.*?-->", lambda _m: f"<!--\n  {banner}.\n  {DERIVED_HEADER_ES}\n-->", text, count=1, flags=re.S)
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_text(text, encoding="utf-8", newline="\n")
        print(f"{dst.relative_to(ROOT)}: derived from {src.name}")

    # iOS: a second localization inside the same catalog. Read afresh, because
    # write_france() has just rewritten the file when both modes run together.
    catalog = json.loads(IOS_CATALOG.read_text(encoding="utf-8"))
    overrides = ES_ES_KEY_OVERRIDES["ios"]
    count = 0
    for key, entry in catalog["strings"].items():
        locs = entry.get("localizations")
        if not locs or "es-419" not in locs:
            continue
        unit = locs["es-419"]["stringUnit"]
        value = overrides.get(key, to_spain(unit["value"]))
        locs["es"] = {"stringUnit": {"state": unit["state"], "value": value}}
        count += 1
    IOS_CATALOG.write_text(
        json.dumps(catalog, ensure_ascii=False, indent=2, separators=(",", " : "), sort_keys=True) + "\n",
        encoding="utf-8", newline="\n")
    print(f"{IOS_CATALOG.relative_to(ROOT)}: {count} es entries derived from es-419")


def main(argv: list[str]) -> int:
    for resx, out, ns, loader in (
        (WINDOWS_RESW, WINDOWS_OUT, "MegaPDF.App", WINDOWS_LOADER),
        (MAC_RESX, MAC_OUT, "MegaPDF.Avalonia", MAC_LOADER),
    ):
        if not resx.exists():
            print(f"skip: {resx.relative_to(ROOT)} does not exist")
            continue
        entries = read_catalogue(resx)
        out.write_text(generate(entries, ns, resx.relative_to(ROOT).as_posix(), loader), encoding="utf-8", newline="\n")
        print(f"{out.relative_to(ROOT)}: {sum(1 for n, _, _ in entries if '.' not in n)} accessors")

    if "pseudo" in argv:
        for src, dst in ((WINDOWS_RESW, WINDOWS_PSEUDO), (MAC_RESX, MAC_PSEUDO)):
            if src.exists():
                write_pseudo(src, dst)
                print(f"{dst.relative_to(ROOT)}: pseudo-locale written")

    if "fr-fr" in argv:
        write_france()
    if "es-es" in argv:
        write_spain()
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
